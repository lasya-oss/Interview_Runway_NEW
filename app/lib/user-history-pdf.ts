import type {
  FeedbackHistory,
  PracticeHistory,
  RoadmapHistory,
  TimelineEvent,
  UserHistoryReport,
} from "@/app/lib/user-history";

const PAGE_WIDTH = 595.28;
const PAGE_HEIGHT = 841.89;
const MARGIN = 51;
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN * 2;
const BODY_TOP = PAGE_HEIGHT - 54;
const BODY_BOTTOM = 48;

const COLOR = {
  navy: "0.027 0.067 0.106",
  navy2: "0.051 0.098 0.149",
  teal: "0.078 0.169 0.220",
  ink: "0.067 0.094 0.153",
  muted: "0.349 0.404 0.459",
  mutedLight: "0.820 0.863 0.886",
  orange: "1 0.420 0.173",
  orangeSoft: "1 0.945 0.918",
  pale: "0.969 0.976 0.988",
  paleAlt: "0.957 0.969 0.980",
  line: "0.851 0.878 0.910",
  white: "1 1 1",
  green: "0.169 0.631 0.431",
} as const;

type Font = "F1" | "F2" | "F3";

type PdfPage = {
  kind: "cover" | "body";
  commands: string[];
  contentCount: number;
};

type TextOptions = {
  font?: Font;
  size?: number;
  color?: string;
  leading?: number;
  maxWidth?: number;
  indent?: number;
};

export function createUserHistoryPdf(report: UserHistoryReport): Uint8Array {
  const document = new UserHistoryPdfDocument(report);
  document.cover();
  document.executiveSummary();
  document.planJourney();
  document.activityTimeline();
  document.assessmentsAndScores();
  document.feedbackHistory();
  document.practiceAndLearning();
  document.humanCalibration();
  document.meetingCopilotAndShowcase();
  document.currentStatusAndNextSteps();
  return document.finish();
}

class UserHistoryPdfDocument {
  private readonly pages: PdfPage[] = [];
  private page: PdfPage | null = null;
  private y = BODY_TOP;

  constructor(private readonly report: UserHistoryReport) {}

  cover() {
    this.page = { kind: "cover", commands: [], contentCount: 1 };
    this.pages.push(this.page);
    const commands = this.page.commands;
    commands.push(fillRect(COLOR.navy, 0, 0, PAGE_WIDTH, PAGE_HEIGHT));
    commands.push(textCommand("F2", 11.2, MARGIN + 31, PAGE_HEIGHT - 52, COLOR.white, "INTERVIEW"));
    commands.push(textCommand("F2", 11.2, MARGIN + 91, PAGE_HEIGHT - 52, COLOR.orange, "RUNWAY"));
    commands.push(strokeCircle("0.443 0.502 0.553", MARGIN + 10, PAGE_HEIGHT - 49, 9, 0.7));
    commands.push(textCommand("F2", 8, MARGIN + 5.5, PAGE_HEIGHT - 51.7, COLOR.white, "//"));
    commands.push(textCommand("F3", 6.7, PAGE_WIDTH - MARGIN - 126, PAGE_HEIGHT - 47, "0.639 0.698 0.737", "HUMAN CALIBRATION / INTERNAL"));
    for (let index = 0; index < 7; index += 1) {
      commands.push(fillRect(COLOR.teal, MARGIN + index * 67, PAGE_HEIGHT - 68, 47, 16));
    }
    commands.push(fillRect(COLOR.orange, MARGIN, PAGE_HEIGHT - 83, CONTENT_WIDTH, 1.7));

    commands.push(textCommand("F2", 8.3, MARGIN + 5, PAGE_HEIGHT - 210, COLOR.orange, "INTERVIEW RUNWAY"));
    const titleLines = wrapText("User History Report", 30, CONTENT_WIDTH - 10, "F2");
    let titleY = PAGE_HEIGHT - 242;
    for (const line of titleLines) {
      commands.push(textCommand("F2", 30, MARGIN + 5, titleY, COLOR.white, line));
      titleY -= 34;
    }

    commands.push(textCommand("F1", 10, MARGIN + 5, titleY - 15, COLOR.mutedLight, "A source-traceable record of the learner journey across Interview Runway."));
    commands.push(fillRect(COLOR.orange, MARGIN + 5, titleY - 42, 119, 3));

    let detailY = titleY - 84;
    commands.push(textCommand("F3", 6.8, MARGIN + 5, detailY, "0.639 0.698 0.737", "LEARNER"));
    detailY -= 19;
    commands.push(textCommand("F2", 15, MARGIN + 5, detailY, COLOR.white, this.report.learner.name ?? "Name not recorded"));
    detailY -= 21;
    for (const line of wrapText(this.report.learner.email, 10.5, CONTENT_WIDTH - 10, "F1")) {
      commands.push(textCommand("F1", 10.5, MARGIN + 5, detailY, COLOR.mutedLight, line));
      detailY -= 15;
    }
    detailY -= 15;
    commands.push(textCommand("F3", 6.8, MARGIN + 5, detailY, "0.639 0.698 0.737", "REPORT GENERATED"));
    detailY -= 17;
    commands.push(textCommand("F1", 10.5, MARGIN + 5, detailY, COLOR.white, formatTimestamp(this.report.generatedAt)));
    detailY -= 34;
    commands.push(textCommand("F3", 6.8, MARGIN + 5, detailY, "0.639 0.698 0.737", "GENERATED BY"));
    detailY -= 17;
    commands.push(textCommand("F1", 10.5, MARGIN + 5, detailY, COLOR.white, this.report.generatedByEmail));

    commands.push(textCommand("F3", 6.5, MARGIN, 27, COLOR.orange, "CONFIDENTIAL / AUTHORIZED VIVID LABS USE"));
    commands.push(textCommand("F3", 6.5, PAGE_WIDTH - MARGIN - 81, 27, "0.639 0.698 0.737", "interviewrunway.com"));
  }

  executiveSummary() {
    this.majorHeading(
      "Executive summary",
      "What the production record can establish",
      "This report separates recorded activity from unavailable history. It does not infer missing dates, scores, sessions, or learner actions.",
    );
    const summary = this.report.executiveSummary;
    this.keyValueGrid([
      ["CURRENT PLAN / ACCESS", summary.currentPlan],
      ["CURRENT STATUS", summary.currentStatus],
      ["FIRST RECORDED ACTIVITY", summary.earliestRecordedAt ? formatRecordedTime(summary.earliestRecordedAt) : "No recorded activity"],
      ["LATEST RECORDED ACTIVITY", summary.latestRecordedAt ? formatRecordedTime(summary.latestRecordedAt) : "No recorded activity"],
      ["VAULT ROADMAP", `${summary.vaultProgressPercent}% complete`],
      ["SECOND SEAT ROADMAP", `${summary.secondSeatProgressPercent}% complete`],
      ["COMPLETED ROADMAP TASKS", `${summary.completedRoadmapTasks} completed`],
      ["PRACTICE", `${summary.completedPracticeSessions} completed / ${summary.attemptedPracticeSessions} attempted`],
      ["LATEST SCORE", summary.latestPracticeScore === null ? "No recorded score" : `${summary.latestPracticeScore}/100`],
      ["BEST PRACTICE SCORE", summary.bestPracticeScore === null ? "No recorded score" : `${summary.bestPracticeScore}/100`],
    ]);
    this.callout(
      "DATA BOUNDARY",
      `Focused learning time: ${formatDuration(summary.focusedSeconds)} account-wide. Roadmap attempts, Library opens, Human Calibration sessions, Meeting Copilot runs, and showcase events are not currently stored as user history.`,
    );
  }

  planJourney() {
    this.majorHeading(
      "Plan and journey",
      "Recorded access and plan signals",
      "Access records show current stored entitlement state. The active QA view is a browser preference and is not a durable learner-history event.",
    );
    this.statusCard(
      this.report.accessHistory.internalFullAccess
        ? "VIVID LABS INTERNAL ACCESS"
        : this.report.executiveSummary.currentStatus.includes("configured")
          ? "CONFIGURED QA ACCESS"
          : "RECORDED PAID ACCESS",
      this.report.executiveSummary.currentStatus,
      this.report.accessHistory.internalFullAccess
        ? "The configured internal-access policy provides Vault, Second Seat, and Human Calibration access. The policy does not store an activation date or plan-transition history."
        : this.report.executiveSummary.currentStatus.includes("configured")
          ? "The current environment grants this account QA access without creating a payment or activation-history record. Stored access and checkout records appear below."
          : "The entries below are the complete access and checkout records currently stored for this account.",
    );

    this.subheading("Entitlements");
    if (!this.report.accessHistory.entitlements.length) {
      this.emptyState("No recorded entitlement entries.");
    } else {
      for (const entitlement of this.report.accessHistory.entitlements) {
        this.recordCard(entitlement.plan, entitlement.status.toUpperCase(), [
          `Created: ${formatRecordedTime(entitlement.createdAt)}`,
          `Latest update: ${formatRecordedTime(entitlement.updatedAt)}`,
          `Source event time: ${formatRecordedTime(entitlement.lastEventAt)}`,
        ]);
      }
    }

    this.subheading("Checkout history");
    if (!this.report.accessHistory.checkouts.length) {
      this.emptyState("No recorded checkout activity.");
    } else {
      for (const checkout of this.report.accessHistory.checkouts) {
        this.recordCard(checkout.plan, checkout.status.toUpperCase(), [
          `Started: ${formatRecordedTime(checkout.createdAt)}`,
          `Latest update: ${formatRecordedTime(checkout.updatedAt)}`,
          `Expiry recorded: ${formatRecordedTime(checkout.expiresAt)}`,
        ]);
      }
    }
  }

  activityTimeline() {
    this.majorHeading(
      "Activity timeline",
      "The learner journey in chronological order",
      "Roadmap completions retain date-only precision. Practice, access, and qualification records preserve their stored timestamps.",
    );
    if (!this.report.timeline.length) {
      this.emptyState("No recorded activity.");
      return;
    }
    for (const event of this.report.timeline) this.timelineCard(event);
  }

  assessmentsAndScores() {
    this.majorHeading(
      "Assessments and scores",
      "Practice evidence across completed attempts",
      "Scores are recomputed from each stored transcript with the current deterministic Second Seat rubric. No immutable rubric version is stored.",
    );
    const scored = this.report.practiceSessions.filter((session) => session.overallScore !== null);
    if (!scored.length) {
      this.emptyState("No recorded scored assessments.");
      return;
    }
    for (const session of scored) this.assessmentCard(session);
  }

  feedbackHistory() {
    this.majorHeading(
      "Feedback history",
      "What was strong, what needs work, and what came next",
      "Each entry is tied to a completed Second Seat practice transcript. Recommendations come from the product's recorded evaluation flow.",
    );
    if (!this.report.feedbackHistory.length) {
      this.emptyState("No recorded feedback.");
      return;
    }
    for (const feedback of this.report.feedbackHistory) {
      this.feedbackCard(feedback);
      const session = this.report.practiceSessions.find((item) => `feedback:${item.id}` === feedback.id);
      if (session?.evidence.length) {
        this.label("QUESTION-LINKED EVIDENCE");
        for (const evidence of session.evidence) {
          this.recordCard(`${evidence.turn}: ${evidence.question}`, evidence.relevance.toUpperCase(), [
            `Response excerpt: ${evidence.excerpt}`,
            `Observation: ${evidence.observation}`,
            `Correction: ${evidence.correction}`,
          ]);
        }
      }
    }
  }

  practiceAndLearning() {
    this.majorHeading(
      "Practice and learning progress",
      "Completed work and recorded attempts",
      "The roadmap stores the current completion set. It does not retain unchecked completions, task attempts, or individual material views.",
    );
    this.keyValueGrid([
      ["ACCOUNT FOCUS TIME", formatDuration(this.report.roadmap.focusedSeconds)],
      ["ATTRIBUTION", "Account-wide only"],
    ]);
    this.paragraph(this.report.roadmap.focusAttribution, { color: COLOR.muted });
    this.roadmapCard(this.report.roadmap.vault);
    this.roadmapCard(this.report.roadmap.secondSeat);

    const unmappedCompletedTasks = this.report.roadmap.unmappedCompletedTasks ?? [];
    if (unmappedCompletedTasks.length) {
      this.subheading("Legacy or unpublished completions");
      this.paragraph(
        "These task identifiers remain in the stored completion set but do not map to the current Vault or Second Seat roadmap. They are retained here without assigning a plan or title that the production record cannot support.",
        { size: 8.3, leading: 11.5, color: COLOR.muted },
      );
      for (const record of unmappedCompletedTasks) {
        this.recordCard(record.title || `Stored task ID: ${record.id}`, "LEGACY / UNMAPPED", [
          record.week === null
            ? `Stored task identifier: ${record.id}`
            : `Legacy roadmap week ${record.week} / stored task identifier: ${record.id}`,
          record.completedAt
            ? `Completion date: ${formatRecordedTime(record.completedAt)}`
            : "Completion date is not recorded.",
        ]);
      }
    }

    this.subheading("Second Seat practice attempts");
    if (!this.report.practiceSessions.length) {
      this.emptyState("No recorded practice attempts.");
    } else {
      for (const session of this.report.practiceSessions) {
        this.recordCard(session.title, session.status.toUpperCase(), [
          `Started: ${formatRecordedTime(session.startedAt)}`,
          session.completedAt ? `Completed: ${formatRecordedTime(session.completedAt)}` : "Completion: Not recorded",
          `Responses recorded: ${session.answerCount}`,
        ]);
      }
    }
  }

  humanCalibration() {
    this.majorHeading(
      "Human Calibration",
      "Qualification and human-coaching history",
      "Only durable Human Calibration records are included. Sample coach-room content is intentionally excluded.",
    );
    this.statusCard("ACCESS", "Human Calibration", this.report.humanCalibration.accessStatus);
    this.subheading("Qualification history");
    if (!this.report.humanCalibration.applications.length) {
      this.emptyState("No recorded qualification activity.");
    } else {
      for (const application of this.report.humanCalibration.applications) {
        this.recordCard("Qualification application", application.status.toUpperCase(), [
          `Submitted: ${formatRecordedTime(application.createdAt)}`,
          `Learner-declared Foundation status: ${humanize(application.phaseOneStatus)}`,
          `Learner-declared Second Seat status: ${humanize(application.phaseTwoStatus)}`,
          `Target role: ${application.targetRole}`,
        ]);
        this.labeledParagraph("VISIBLE GAP", application.visibleGap);
        this.labeledParagraph("ADDITIONAL CONTEXT", application.additionalContext || "None recorded");
      }
    }
    this.subheading("Sessions and feedback");
    this.emptyState(this.report.humanCalibration.sessionHistoryStatus);
    this.emptyState(this.report.humanCalibration.feedbackHistoryStatus);
  }

  meetingCopilotAndShowcase() {
    this.majorHeading(
      "Meeting Copilot and showcase history",
      "Only server-recorded activity can appear here",
      "The report does not import local-device data, browser-only analytics, demo state, or static Library/replay content as learner history.",
    );
    this.statusCard("MEETING COPILOT", "Usage history", this.report.meetingCopilot.status);
    this.statusCard("API / SHOWCASE", "Recorded activity", this.report.apiAndShowcase.status);
  }

  currentStatusAndNextSteps() {
    this.majorHeading(
      "Current status and next steps",
      "The latest supported view",
      "Next steps are shown only when the product's recorded practice feedback or roadmap state supplies one.",
    );
    this.keyValueGrid([
      ["CURRENT PLAN / ACCESS", this.report.executiveSummary.currentPlan],
      ["CURRENT STATUS", this.report.executiveSummary.currentStatus],
      ["LATEST ACTIVITY", this.report.currentState.latestRecordedActivity?.title ?? "No recorded activity"],
      ["LATEST FEEDBACK", this.report.currentState.latestFeedback],
    ]);
    this.callout("NEXT RECORDED STEP", this.report.currentState.nextStep);
    this.subheading("Coverage and limitations");
    const coverage = [
      ["Vault access and checkout", this.report.accessHistory.entitlements.length || this.report.accessHistory.checkouts.length ? "Recorded entries included" : "No recorded activity"],
      ["Roadmap completion", this.report.executiveSummary.completedRoadmapTasks ? "Current completions included" : "No recorded activity"],
      ["Second Seat practice and feedback", this.report.practiceSessions.length ? "Recorded entries included" : "No recorded activity"],
      ["Human Calibration qualification", this.report.humanCalibration.applications.length ? "Recorded entries included" : "No recorded activity"],
      ["Human Calibration sessions", "Not stored"],
      ["Meeting Copilot", "Not stored in Interview Runway"],
      ["API / showcase", "Not stored as user history"],
      ["Library opens", "Not stored"],
    ];
    for (const [label, value] of coverage) this.recordCard(label, value.toUpperCase(), []);
  }

  finish(): Uint8Array {
    this.addBodyHeadersAndFooters();
    return serializePdf(this.pages, this.report);
  }

  private majorHeading(kicker: string, title: string, description: string) {
    if (!this.page || this.page.kind === "cover" || this.y < 415) this.newBodyPage();
    else {
      this.ensure(34);
      this.page!.commands.push(strokeLine(COLOR.line, MARGIN, this.y, PAGE_WIDTH - MARGIN, this.y, 0.6));
      this.y -= 28;
    }
    this.label(kicker.toUpperCase());
    this.heading(title, 19, 23);
    this.paragraph(description, { size: 9.4, leading: 13.4, color: COLOR.muted });
    this.y -= 7;
  }

  private subheading(value: string) {
    const lines = wrapText(value, 12.8, CONTENT_WIDTH, "F2");
    // Keep the heading with the first normal card/content block.
    this.ensure(lines.length * 15 + 150);
    this.y -= 7;
    for (const line of lines) {
      this.page!.commands.push(textCommand("F2", 12.8, MARGIN, this.y, COLOR.navy2, line));
      this.y -= 15;
    }
    this.y -= 6;
    this.page!.contentCount += 1;
  }

  private heading(value: string, size = 18, leading = 21) {
    const lines = wrapText(value, size, CONTENT_WIDTH, "F2");
    this.ensure(lines.length * leading + 8);
    for (const line of lines) {
      this.page!.commands.push(textCommand("F2", size, MARGIN, this.y, COLOR.navy2, line));
      this.y -= leading;
    }
    this.y -= 4;
    this.page!.contentCount += 1;
  }

  private label(value: string) {
    const safe = safeText(value).toUpperCase();
    this.ensure(15);
    this.page!.commands.push(textCommand("F2", 7.6, MARGIN, this.y, COLOR.orange, safe));
    this.y -= 14;
    this.page!.contentCount += 1;
  }

  private paragraph(value: string, options: TextOptions = {}) {
    const font = options.font ?? "F1";
    const size = options.size ?? 9.2;
    const leading = options.leading ?? 13.2;
    const indent = options.indent ?? 0;
    const width = options.maxWidth ?? CONTENT_WIDTH - indent;
    const lines = wrapText(value || "No recorded activity.", size, width, font);
    for (const line of lines) {
      this.ensure(leading + 2);
      this.page!.commands.push(textCommand(font, size, MARGIN + indent, this.y, options.color ?? COLOR.ink, line));
      this.y -= leading;
    }
    this.y -= 5;
    this.page!.contentCount += 1;
  }

  private labeledParagraph(label: string, value: string) {
    const size = 8.3;
    const leading = 11.5;
    const lines = wrapText(value || "No recorded activity.", size, CONTENT_WIDTH - 14, "F1");
    this.ensure(14 + leading + 7);
    this.label(label);
    for (const [index, line] of lines.entries()) {
      if (this.y - leading - 2 < BODY_BOTTOM) {
        this.newBodyPage();
        this.label(`${label} / CONTINUED`);
      }
      this.page!.commands.push(textCommand("F1", size, MARGIN + 12, this.y, COLOR.ink, line));
      this.y -= leading;
      if (index === lines.length - 1) this.y -= 7;
    }
    this.page!.contentCount += 1;
  }

  private keyValueGrid(items: readonly (readonly [string, string])[]) {
    const gap = 8;
    const columnWidth = (CONTENT_WIDTH - gap) / 2;
    for (let index = 0; index < items.length; index += 2) {
      const row = items.slice(index, index + 2);
      const prepared = row.map(([label, value]) => ({
        label: safeText(label).toUpperCase(),
        lines: wrapText(value, 9.3, columnWidth - 24, "F2"),
      }));
      const height = Math.max(...prepared.map((item) => 34 + item.lines.length * 12), 58);
      this.ensure(height + gap);
      for (const [column, item] of prepared.entries()) {
        const x = MARGIN + column * (columnWidth + gap);
        const bottom = this.y - height + 8;
        this.page!.commands.push(fillRect(COLOR.paleAlt, x, bottom, columnWidth, height));
        this.page!.commands.push(strokeRect(COLOR.line, x, bottom, columnWidth, height, 0.6));
        this.page!.commands.push(textCommand("F3", 6.6, x + 12, this.y - 14, COLOR.orange, item.label));
        let lineY = this.y - 33;
        for (const line of item.lines) {
          this.page!.commands.push(textCommand("F2", 9.3, x + 12, lineY, COLOR.navy2, line));
          lineY -= 12;
        }
      }
      this.y -= height + gap;
      this.page!.contentCount += row.length;
    }
    this.y -= 4;
  }

  private callout(label: string, value: string) {
    const lines = wrapText(value, 9.1, CONTENT_WIDTH - 34, "F2");
    const height = 35 + lines.length * 12.4;
    this.ensure(height + 8);
    const bottom = this.y - height + 6;
    this.page!.commands.push(fillRect(COLOR.orangeSoft, MARGIN, bottom, CONTENT_WIDTH, height));
    this.page!.commands.push(fillRect(COLOR.orange, MARGIN, bottom, 3, height));
    this.page!.commands.push(textCommand("F2", 7.2, MARGIN + 15, this.y - 13, COLOR.orange, safeText(label).toUpperCase()));
    let lineY = this.y - 31;
    for (const line of lines) {
      this.page!.commands.push(textCommand("F2", 9.1, MARGIN + 15, lineY, COLOR.ink, line));
      lineY -= 12.4;
    }
    this.y -= height + 8;
    this.page!.contentCount += 1;
  }

  private emptyState(value: string) {
    const lines = wrapText(value, 8.8, CONTENT_WIDTH - 30, "F1");
    const height = 24 + lines.length * 12.5;
    this.ensure(height + 6);
    const bottom = this.y - height + 5;
    this.page!.commands.push(fillRect(COLOR.pale, MARGIN, bottom, CONTENT_WIDTH, height));
    this.page!.commands.push(strokeRect(COLOR.line, MARGIN, bottom, CONTENT_WIDTH, height, 0.5));
    let lineY = this.y - 19;
    for (const line of lines) {
      this.page!.commands.push(textCommand("F1", 8.8, MARGIN + 14, lineY, COLOR.muted, line));
      lineY -= 12.5;
    }
    this.y -= height + 6;
    this.page!.contentCount += 1;
  }

  private statusCard(label: string, title: string, detail: string) {
    const titleLines = wrapText(title, 13, CONTENT_WIDTH - 34, "F2");
    const detailLines = wrapText(detail, 8.8, CONTENT_WIDTH - 34, "F1");
    const height = 44 + titleLines.length * 16 + detailLines.length * 12.5;
    this.ensure(height + 8);
    const bottom = this.y - height + 6;
    this.page!.commands.push(fillRect(COLOR.navy2, MARGIN, bottom, CONTENT_WIDTH, height));
    this.page!.commands.push(textCommand("F3", 6.8, MARGIN + 16, this.y - 15, COLOR.orange, safeText(label).toUpperCase()));
    let lineY = this.y - 36;
    for (const line of titleLines) {
      this.page!.commands.push(textCommand("F2", 13, MARGIN + 16, lineY, COLOR.white, line));
      lineY -= 16;
    }
    lineY -= 4;
    for (const line of detailLines) {
      this.page!.commands.push(textCommand("F1", 8.8, MARGIN + 16, lineY, COLOR.mutedLight, line));
      lineY -= 12.5;
    }
    this.y -= height + 8;
    this.page!.contentCount += 1;
  }

  private recordCard(title: string, state: string, details: readonly string[]) {
    const titleWidth = CONTENT_WIDTH - 145;
    const titleLines = wrapText(title, 9.5, titleWidth, "F2");
    const stateLines = wrapText(state, 6.2, 104, "F3");
    const detailLines = details.flatMap((detail) => wrapText(detail, 8.1, CONTENT_WIDTH - 30, "F1"));
    const height = 27 + Math.max(titleLines.length * 12, stateLines.length * 9) + detailLines.length * 11.2 + (detailLines.length ? 9 : 0);
    this.ensure(height + 6);
    const bottom = this.y - height + 5;
    this.page!.commands.push(fillRect(COLOR.pale, MARGIN, bottom, CONTENT_WIDTH, height));
    this.page!.commands.push(strokeRect(COLOR.line, MARGIN, bottom, CONTENT_WIDTH, height, 0.5));
    let titleY = this.y - 18;
    for (const line of titleLines) {
      this.page!.commands.push(textCommand("F2", 9.5, MARGIN + 13, titleY, COLOR.navy2, line));
      titleY -= 12;
    }
    let stateY = this.y - 17;
    for (const line of stateLines) {
      this.page!.commands.push(textCommand("F3", 6.2, PAGE_WIDTH - MARGIN - 116, stateY, COLOR.orange, line));
      stateY -= 9;
    }
    let detailY = this.y - 18 - titleLines.length * 12 - 7;
    for (const line of detailLines) {
      this.page!.commands.push(textCommand("F1", 8.1, MARGIN + 13, detailY, COLOR.muted, line));
      detailY -= 11.2;
    }
    this.y -= height + 6;
    this.page!.contentCount += 1;
  }

  private timelineCard(event: TimelineEvent) {
    const timestamp = event.precision === "date"
      ? `${event.timestamp} / DATE ONLY`
      : formatTimestamp(event.timestamp);
    this.recordCard(`${timestamp} - ${event.title}`, `${event.area} / ${event.state}`, [event.detail, `Source: ${event.source}`]);
  }

  private assessmentCard(session: PracticeHistory) {
    const overall = session.overallScore ?? 0;
    const delta = session.scoreChange === null ? "First scored attempt" : `${formatSigned(session.scoreChange)} vs previous scored attempt`;
    const baseHeight = 78
      + scoreBarHeight()
      + session.dimensions.reduce((height, dimension) => height + scoreBarHeight(dimension.note), 0);
    this.ensure(baseHeight + 14);
    this.label(`${session.category} / ${formatRecordedTime(session.completedAt ?? session.updatedAt)}`);
    this.heading(session.title, 13, 16);
    this.paragraph(`Overall score ${overall}/100. ${delta}.`, { size: 8.7, leading: 12, color: COLOR.muted });
    this.scoreBar("Overall", overall);
    for (const dimension of session.dimensions) this.scoreBar(dimension.label, dimension.score, dimension.note);
    this.y -= 7;
  }

  private scoreBar(label: string, score: number, note?: string) {
    const safeScore = Math.max(0, Math.min(100, Math.round(score)));
    const noteLines = note ? wrapText(note, 7.5, CONTENT_WIDTH, "F1") : [];
    const height = scoreBarHeight(note) - 3;
    this.ensure(height + 3);
    this.page!.commands.push(textCommand("F2", 7.8, MARGIN, this.y - 8, COLOR.teal, safeText(label)));
    this.page!.commands.push(fillRect(COLOR.line, MARGIN + 108, this.y - 8, 210, 4));
    this.page!.commands.push(fillRect(safeScore >= 70 ? COLOR.green : COLOR.orange, MARGIN + 108, this.y - 8, 2.1 * safeScore, 4));
    this.page!.commands.push(textCommand("F3", 7.2, MARGIN + 328, this.y - 10, COLOR.ink, `${safeScore}/100`));
    let noteY = this.y - 22;
    for (const line of noteLines) {
      this.page!.commands.push(textCommand("F1", 7.5, MARGIN, noteY, COLOR.muted, line));
      noteY -= 9.5;
    }
    this.y -= height + 3;
    this.page!.contentCount += 1;
  }

  private feedbackCard(feedback: FeedbackHistory) {
    this.ensure(118);
    this.label(`${formatRecordedTime(feedback.date)} / ${feedback.source}`);
    this.heading(`${feedback.relatedActivity} - ${feedback.score}/100`, 13, 16);
    if (feedback.scoreChange !== null) {
      this.paragraph(`Score movement: ${formatSigned(feedback.scoreChange)} from the previous scored attempt.`, { size: 8.5, leading: 11.5, color: COLOR.muted });
    }
    this.bulletGroup("WHAT WAS DONE WELL", feedback.strengths);
    this.bulletGroup("WHAT NEEDS IMPROVEMENT", feedback.improvements);
    this.bulletGroup("RECOMMENDATIONS", feedback.recommendations);
  }

  private bulletGroup(label: string, values: readonly string[]) {
    const firstContentHeight = values.length
      ? wrapText(values[0], 8.4, CONTENT_WIDTH - 22, "F1").length * 11.7 + 4
      : 11.4 + 7;
    this.ensure(15 + firstContentHeight);
    this.label(label);
    if (!values.length) {
      this.paragraph("No recorded item.", { size: 8.4, leading: 11.4, color: COLOR.muted, indent: 12 });
      return;
    }
    for (const value of values) {
      const lines = wrapText(value, 8.4, CONTENT_WIDTH - 22, "F1");
      this.ensure(lines.length * 11.7 + 4);
      this.page!.commands.push(fillRect(COLOR.orange, MARGIN + 2, this.y - 5, 4, 1.2));
      for (const line of lines) {
        this.page!.commands.push(textCommand("F1", 8.4, MARGIN + 14, this.y, COLOR.ink, line));
        this.y -= 11.7;
      }
      this.y -= 2;
      this.page!.contentCount += 1;
    }
    this.y -= 4;
  }

  private roadmapCard(roadmap: RoadmapHistory) {
    this.subheading(roadmap.label);
    this.keyValueGrid([
      ["PROGRESS", `${roadmap.progressPercent}%`],
      ["COMPLETED", `${roadmap.completedTaskCount} of ${roadmap.totalTaskCount} tasks`],
    ]);
    this.paragraph(roadmap.attemptTrackingStatus, { size: 8.3, leading: 11.5, color: COLOR.muted });
    if (!roadmap.completedTasks.length) {
      this.emptyState("No recorded completed roadmap tasks.");
      return;
    }
    for (const task of roadmap.completedTasks) {
      this.recordCard(`Week ${task.week} - ${task.title}`, task.completedAt ? "COMPLETED" : "COMPLETION DATE NOT RECORDED", [
        task.meta,
        task.completedAt ? `Completion date: ${task.completedAt} (time not recorded)` : "The task is in the completed set, but no completion date is stored.",
      ]);
    }
  }

  private newBodyPage() {
    this.page = { kind: "body", commands: [], contentCount: 0 };
    this.pages.push(this.page);
    this.y = BODY_TOP - 26;
  }

  private ensure(height: number) {
    if (!this.page || this.page.kind === "cover" || this.y - height < BODY_BOTTOM) this.newBodyPage();
  }

  private addBodyHeadersAndFooters() {
    const total = this.pages.length;
    this.pages.forEach((page, index) => {
      if (page.kind !== "body") return;
      page.commands.unshift(
        textCommand("F2", 7.2, MARGIN, PAGE_HEIGHT - 24, COLOR.navy2, "INTERVIEWRUNWAY / HUMAN CALIBRATION"),
        textCommand("F3", 6.1, PAGE_WIDTH - MARGIN - 104, PAGE_HEIGHT - 24, "0.529 0.588 0.639", "USER HISTORY REPORT"),
        strokeLine(COLOR.line, MARGIN, PAGE_HEIGHT - 36, PAGE_WIDTH - MARGIN, PAGE_HEIGHT - 36, 0.6),
      );
      page.commands.push(
        strokeLine(COLOR.line, MARGIN, 34, PAGE_WIDTH - MARGIN, 34, 0.6),
        textCommand("F3", 6.1, MARGIN, 22, COLOR.orange, "CONFIDENTIAL / AUTHORIZED VIVID LABS USE"),
        textCommand("F3", 6.1, PAGE_WIDTH - MARGIN - 48, 22, "0.529 0.588 0.639", `${String(index + 1).padStart(2, "0")} / ${String(total).padStart(2, "0")}`),
      );
    });
  }
}

function serializePdf(pages: readonly PdfPage[], report: UserHistoryReport): Uint8Array {
  const objects: string[] = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>",
  ];
  const pageObjectNumbers: number[] = [];
  for (const page of pages) {
    const pageObjectNumber = objects.length + 1;
    const contentObjectNumber = objects.length + 2;
    pageObjectNumbers.push(pageObjectNumber);
    const stream = page.commands.join("\n");
    objects.push(
      `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE_WIDTH} ${PAGE_HEIGHT}] /Resources << /Font << /F1 3 0 R /F2 4 0 R /F3 5 0 R >> >> /Contents ${contentObjectNumber} 0 R >>`,
      `<< /Length ${bytesFor(stream).length} >>\nstream\n${stream}\nendstream`,
    );
  }
  objects[1] = `<< /Type /Pages /Kids [${pageObjectNumbers.map((number) => `${number} 0 R`).join(" ")}] /Count ${pages.length} >>`;
  const infoObjectNumber = objects.length + 1;
  objects.push(
    `<< /Title (${escapePdfString(safeText(`Interview Runway User History Report - ${report.learner.email}`))}) /Author (InterviewRunway) /Subject (Authorized internal learner history report) /Creator (InterviewRunway) /CreationDate (${pdfDate(report.generatedAt)}) >>`,
  );

  const chunks: Uint8Array[] = [bytesFor("%PDF-1.4\n%\u00e2\u00e3\u00cf\u00d3\n")];
  const offsets = [0];
  let offset = chunks[0].length;
  objects.forEach((object, index) => {
    offsets[index + 1] = offset;
    const chunk = bytesFor(`${index + 1} 0 obj\n${object}\nendobj\n`);
    chunks.push(chunk);
    offset += chunk.length;
  });
  const xrefOffset = offset;
  chunks.push(bytesFor([
    `xref\n0 ${objects.length + 1}`,
    "0000000000 65535 f ",
    ...offsets.slice(1).map((value) => `${String(value).padStart(10, "0")} 00000 n `),
    `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R /Info ${infoObjectNumber} 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`,
  ].join("\n")));
  return concatBytes(chunks);
}

function wrapText(value: string, size: number, maxWidth: number, font: Font): string[] {
  const normalized = safeText(value).replace(/\s+/g, " ").trim() || "No recorded activity.";
  const words = normalized.split(" ");
  const lines: string[] = [];
  let line = "";
  for (const word of words) {
    const parts = splitLongWord(word, size, maxWidth, font);
    for (const part of parts) {
      const candidate = line ? `${line} ${part}` : part;
      if (estimatedWidth(candidate, size, font) <= maxWidth) {
        line = candidate;
      } else {
        if (line) lines.push(line);
        line = part;
      }
    }
  }
  if (line) lines.push(line);
  return lines.length ? lines : ["No recorded activity."];
}

function splitLongWord(word: string, size: number, maxWidth: number, font: Font) {
  if (estimatedWidth(word, size, font) <= maxWidth) return [word];
  const parts: string[] = [];
  let remaining = word;
  const averageWidth = font === "F3" ? size * 0.6 : size * 0.52;
  const maxCharacters = Math.max(4, Math.floor(maxWidth / averageWidth));
  while (remaining.length > maxCharacters) {
    parts.push(`${remaining.slice(0, maxCharacters - 1)}-`);
    remaining = remaining.slice(maxCharacters - 1);
  }
  if (remaining) parts.push(remaining);
  return parts;
}

function estimatedWidth(value: string, size: number, font: Font) {
  if (font === "F3") return value.length * size * 0.6;
  return [...value].reduce((sum, character) => {
    if (/[ilI1.,' ]/.test(character)) return sum + size * 0.26;
    if (/[MW@%]/.test(character)) return sum + size * 0.84;
    return sum + size * (font === "F2" ? 0.55 : 0.51);
  }, 0);
}

function scoreBarHeight(note?: string) {
  const noteLines = note ? wrapText(note, 7.5, CONTENT_WIDTH, "F1") : [];
  return Math.max(24, 20 + noteLines.length * 9.5) + 3;
}

function safeText(value: string) {
  const replacements: Record<string, string> = {
    "\u2018": "'", "\u2019": "'", "\u201c": "\"", "\u201d": "\"",
    "\u2013": "-", "\u2014": "-", "\u2022": "-", "\u2192": "->",
    "\u00d7": "x", "\u00a0": " ", "\u00b7": "/", "\u2026": "...",
  };
  return String(value ?? "")
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[\r\n\t]+/g, " ")
    .replace(/[^\x20-\x7e]/g, (character) => replacements[character] ?? "?");
}

function textCommand(font: Font, size: number, x: number, y: number, color: string, value: string) {
  return `BT /${font} ${number(size)} Tf ${color} rg 1 0 0 1 ${number(x)} ${number(y)} Tm (${escapePdfString(safeText(value))}) Tj ET`;
}

function fillRect(color: string, x: number, y: number, width: number, height: number) {
  return `${color} rg ${number(x)} ${number(y)} ${number(width)} ${number(height)} re f`;
}

function strokeRect(color: string, x: number, y: number, width: number, height: number, lineWidth: number) {
  return `${color} RG ${number(lineWidth)} w ${number(x)} ${number(y)} ${number(width)} ${number(height)} re S`;
}

function strokeLine(color: string, x1: number, y1: number, x2: number, y2: number, lineWidth: number) {
  return `${color} RG ${number(lineWidth)} w ${number(x1)} ${number(y1)} m ${number(x2)} ${number(y2)} l S`;
}

function strokeCircle(color: string, x: number, y: number, radius: number, lineWidth: number) {
  const c = radius * 0.5522847498;
  return `${color} RG ${number(lineWidth)} w ${number(x + radius)} ${number(y)} m ${number(x + radius)} ${number(y + c)} ${number(x + c)} ${number(y + radius)} ${number(x)} ${number(y + radius)} c ${number(x - c)} ${number(y + radius)} ${number(x - radius)} ${number(y + c)} ${number(x - radius)} ${number(y)} c ${number(x - radius)} ${number(y - c)} ${number(x - c)} ${number(y - radius)} ${number(x)} ${number(y - radius)} c ${number(x + c)} ${number(y - radius)} ${number(x + radius)} ${number(y - c)} ${number(x + radius)} ${number(y)} c S`;
}

function escapePdfString(value: string) {
  return value.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
}

function bytesFor(value: string) {
  return new TextEncoder().encode(value);
}

function concatBytes(chunks: readonly Uint8Array[]) {
  const totalLength = chunks.reduce((sum, chunk) => sum + chunk.length, 0);
  const result = new Uint8Array(totalLength);
  let offset = 0;
  for (const chunk of chunks) {
    result.set(chunk, offset);
    offset += chunk.length;
  }
  return result;
}

function number(value: number) {
  return Number(value.toFixed(2));
}

function formatTimestamp(value: string) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return safeText(value);
  return date.toISOString().replace("T", " ").replace(".000Z", " UTC");
}

function formatRecordedTime(value: string) {
  return /^\d{4}-\d{2}-\d{2}$/.test(value) ? `${value} (date only)` : formatTimestamp(value);
}

function formatDuration(seconds: number) {
  const safeSeconds = Math.max(0, Math.floor(seconds));
  const hours = Math.floor(safeSeconds / 3600);
  const minutes = Math.floor((safeSeconds % 3600) / 60);
  return hours ? `${hours}h ${minutes}m` : `${minutes}m`;
}

function humanize(value: string) {
  return value.replaceAll("_", " ");
}

function formatSigned(value: number) {
  return value > 0 ? `+${value}` : String(value);
}

function pdfDate(value: string) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "";
  return `D:${date.toISOString().replace(/[-:T]/g, "").slice(0, 14)}Z`;
}
